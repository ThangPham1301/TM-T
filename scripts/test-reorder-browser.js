// Run through Playwright CLI against test-reorder-demo.py --keep; disposable data only.
async (page) => {
  const origin = 'http://127.0.0.1:13098';
  if (!page.url().startsWith(origin + '/')) throw new Error('Open the disposable reorder fixture first');
  page.setDefaultTimeout(15000);
  const checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  const api = async (path, body) => {
    const response = body === undefined ? await page.request.get(origin + '/api/store/' + path)
      : await page.request.post(origin + '/api/store/' + path, {headers:{Origin:origin,'Idempotency-Key':crypto.randomUUID()},data:body});
    if (!response.ok()) throw new Error(`${path}: ${response.status()} ${await response.text()}`);
    return response.json();
  };
  await page.setViewportSize({width:1440,height:1000});
  await page.context().clearCookies();
  await api('auth/login',{email:'reorder-alice@example.invalid',password:'disposable-review-password'});
  const initial = await api('state');
  const source = initial.orders.find(order=>order.number==='GH-REORDER1');
  const products = await api('products');
  const productA = products.find(p=>p.id===source.items[0].productId);
  const productB = products.find(p=>p.id===source.items[1].productId);
  const otherProduct = products.find(p=>p.stock>0 && !source.items.some(item=>item.productId===p.id));
  let cart = await api('cart/summary');
  await api('commerce',{action:'cart-set',productId:otherProduct.id,quantity:2,cartToken:cart.cartToken});
  cart = await api('cart/summary');
  await page.goto(origin + '/account/orders');
  const search = page.getByPlaceholder('Tìm theo mã đơn (vd: GH-2025-8821), tên người nhận...');
  const card = page.locator('article.orders-article-card');
  for (const status of ['PLACED','CONFIRMED','PACKED','SHIPPED','CANCELLED','DELIVERY_FAILED','RETURNED']) {
    const order = initial.orders.find(row=>row.status===status);
    await search.fill(order.number);
    await card.first().waitFor();
    check(await card.count()===1, 'exact history filter for ' + status);
    const buttons = card.getByRole('button',{name:/Mua lại|Đặt lại đơn/});
    check(await buttons.count() === (['CANCELLED','DELIVERY_FAILED','RETURNED'].includes(status)?1:0), 'reorder visibility follows ' + status);
  }
  await search.fill(source.number);
  await card.getByRole('button',{name:/Mua lại/}).click();
  const dialog = page.getByRole('dialog',{name:/Mua lại từ đơn/});
  await dialog.getByText('Sản phẩm hiện hết hàng.',{exact:false}).waitFor();
  check(await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).isDisabled(), 'unavailable selection blocks confirmation');
  check((await api('cart/summary')).cartToken===cart.cartToken, 'opening reorder leaves existing cart intact');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  check((await api('cart/summary')).cartToken===cart.cartToken, 'cancelling reorder preserves cart');
  await card.getByRole('button',{name:/Mua lại/}).click();
  await dialog.getByRole('checkbox',{name:'Chọn '+productB.name,exact:true}).waitFor();
  await dialog.getByRole('checkbox',{name:'Chọn '+productB.name,exact:true}).uncheck();
  const quote = page.waitForResponse(response=>response.url().endsWith('/reorder/preview'));
  await dialog.getByRole('button',{name:'Cập nhật báo giá',exact:true}).click();
  check((await quote).ok(), 'explicitly removed product is requoted');
  await dialog.getByText('Tổng dự kiến',{exact:true}).waitFor();
  check(await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).isDisabled(), 'existing-cart replacement needs explicit consent');
  await dialog.getByRole('checkbox',{name:/Tôi đồng ý thay/}).check();
  const quantity = dialog.getByRole('spinbutton',{name:'Số lượng mua lại '+productA.name,exact:true});
  await quantity.fill('3');
  check(await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).isDisabled(), 'quantity changes invalidate old preview');
  const requoted = page.waitForResponse(response=>response.url().endsWith('/reorder/preview'));
  await dialog.getByRole('button',{name:'Cập nhật báo giá',exact:true}).click();
  check((await requoted).ok(), 'customer-adjusted quantity gets a fresh quote');
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('dialog button')).find(b=>b.textContent==='Tiếp tục thanh toán')?.disabled);
  await page.setViewportSize({width:390,height:844});
  check(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth), 'mobile reorder dialog has no horizontal overflow');
  await page.screenshot({path:'output/playwright/reorder-mobile.png'});
  await page.route('**/api/store/orders/*/reorder', route=>route.fulfill({status:409,contentType:'application/json',body:'{"message":"Synthetic stale preview"}'}));
  await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).click();
  await dialog.getByText('Thông tin đơn, giá hoặc giỏ hàng vừa thay đổi.',{exact:false}).waitFor();
  await page.unroute('**/api/store/orders/*/reorder');
  check((await api('cart/summary')).cartToken===cart.cartToken, 'stale confirmation leaves the cart intact while preview refreshes');
  check(await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).isEnabled(), 'fresh preview permits an explicit retry after a conflict');
  const confirmation = page.waitForResponse(response=>/\/orders\/.+\/reorder$/.test(response.url()) && response.request().method()==='POST');
  await dialog.getByRole('button',{name:'Tiếp tục thanh toán',exact:true}).click();
  check((await confirmation).ok(), 'reviewed selection confirms successfully');
  await page.waitForURL(origin + '/checkout?reorder=' + source.id);
  const recipient = page.getByRole('textbox',{name:/Họ và tên người nhận/});
  await recipient.waitFor();
  check(await recipient.inputValue()===source.recipient, 'checkout prefills old recipient rather than profile or saved address');
  check(await page.getByRole('textbox',{name:/Số điện thoại nhận hàng/}).inputValue()===source.phone, 'checkout prefills old phone');
  check(await page.getByRole('textbox',{name:/Địa chỉ giao hàng/}).inputValue()===source.address, 'checkout prefills old address');
  check((await api('state')).orders.length===initial.orders.length, 'confirmation only prepares a cart, not an order');
  cart = await api('cart/summary');
  check(cart.items.length===1 && cart.items[0].productId===productA.id && cart.items[0].quantity===3, 'replacement contains exactly reviewed product and quantity');
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/reorder-checkout-desktop.png'});
  const edit = page.getByRole('link',{name:'Sửa ✎',exact:true});
  check((await edit.getAttribute('href')).includes('reorder='+source.id), 'cart edit retains reorder source');
  await edit.click();
  await page.waitForURL(origin + '/cart?reorder=' + source.id);
  const cartQuantity = page.getByRole('spinbutton',{name:'Số lượng '+productA.name,exact:true});
  await cartQuantity.waitFor();
  const cartUpdated = page.waitForResponse(response=>response.url().endsWith('/api/store/commerce') && response.request().method()==='POST');
  await cartQuantity.fill('4');
  await cartQuantity.blur();
  check((await cartUpdated).ok(), 'cart quantities remain editable after reorder');
  await page.getByRole('button',{name:/Tiến hành đặt hàng/}).click();
  await page.waitForURL(origin + '/checkout?reorder=' + source.id);
  await recipient.waitFor();
  check(await recipient.inputValue()===source.recipient, 'recipient source survives cart-to-checkout round trip');
  await page.getByRole('radio',{name:/Saved Address Recipient/}).check();
  check(await recipient.count()===0, 'customer can choose a saved address instead');
  await page.getByRole('radio',{name:'Nhập địa chỉ cho đơn này',exact:true}).check();
  await recipient.fill('Browser Adjusted Recipient');
  await page.getByRole('textbox',{name:/Số điện thoại nhận hàng/}).fill('0955555555');
  await page.getByRole('textbox',{name:/Địa chỉ giao hàng/}).fill('Browser adjusted address');
  const placed = page.waitForResponse(response=>response.url().endsWith('/api/store/commerce') && response.request().method()==='POST');
  await page.getByRole('button',{name:'Xác nhận đặt hàng',exact:true}).click();
  const response = await placed;
  check(response.ok(), 'explicit checkout creates the new order');
  const newOrder = await response.json();
  check(newOrder.id!==source.id && newOrder.paymentStatus==='UNPAID' && newOrder.items[0].quantity===4, 'new order has its own unpaid state and adjusted quantity');
  check(newOrder.recipient==='Browser Adjusted Recipient' && newOrder.address==='Browser adjusted address', 'new order uses customer-adjusted recipient details');
  const finalState = await api('state');
  check(finalState.user.address==='Current profile address' && finalState.addresses.length===1 && finalState.addresses[0].recipient==='Saved Address Recipient', 'profile and address book are unchanged');
  check(errors.length===0, 'no browser runtime errors');
  return {passed:true,count:checks.length,checks};
}
